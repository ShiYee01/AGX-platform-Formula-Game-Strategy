"""Embed reproducible public numeric geometry; keep the submission at two files."""
import hashlib
import json
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
START='# BEGIN PUBLIC MAP DATA'
END='# END PUBLIC MAP DATA'


def generated():
    out=[START+' (generated by tools/embed_v4_maps.py; curvature 1/m, grade m/m)','MAP_DATA = (']
    for name in ('parkland','highland','crossover'):
        path=ROOT/f'data/racing-{name}.mapdata.json'
        d=json.loads(path.read_text());points=d['centerline'];length=d['length_m']
        assert all(abs(p['s_m']-i*length/len(points))<1e-7 for i,p in enumerate(points))
        out.extend([f'    # {name}: {len(points)} uniform samples; public map SHA256 {hashlib.sha256(path.read_bytes()).hexdigest()}',f'    ({length!r},'])
        for key,digits in [('curvature_1pm',7),('grade_dz_ds',5)]:
            vals=[repr(round(p[key],digits)) for p in points]
            out.append('     (')
            out.extend('      '+','.join(vals[i:i+10])+',' for i in range(0,len(vals),10))
            out.append('     ),')
        out.append('    ),')
    out.extend([')',END]);return '\n'.join(out)


def build():
    p=ROOT/'agent/agent.py';s=p.read_text();a=s.index(START);b=s.index(END,a)+len(END)
    s=s[:a]+generated()+s[b:]
    assert len(s.encode())<256*1024
    p.write_text(s)


if __name__=='__main__':build()
